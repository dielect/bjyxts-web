def draw_defend2_text(actor,bid=0)
  if actor.is_a?(Game_Actor)
    user="你"
  else
    user=actor.name
  end
  words=["但是#{user}身子一侧，用手中兵刃架开",
  "只听见“将”一声，被#{user}格开了",
  "但是被#{user}用手中兵刃架开",
  "结果“当”地一声，被#{user}挡开了",
  "结果被#{user}挡开了",
  "#{user}没料到这一击却打空，原来打中的只是个影子"]
  id=rand(5)
  id=bid if bid !=0
  return words[id]+'|'+id.to_s
end
