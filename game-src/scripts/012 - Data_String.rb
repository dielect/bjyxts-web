module RPG
  class System
    # 增加装备位置
    attr_accessor :armor5
    attr_accessor :armor6
    attr_accessor :armor7
    def initialize
      @armor5=""
      @armor6=""
      @armor7=""
    end
    def armor5
      return "披风"
    end
    def armor6
      return "腰带"
    end
    def armor7
      return "钓竿"
    end
  end
  class Armor
    # 增加3个装备分类
    def kind
      if self.id==19
        return 4
      else
        if self.id==30
          return 5
        else
          if self.id==31
            return 6
          else
            return @kind
          end
        end
      end
    end
  end
  class Enemy
    attr_accessor :lv
    alias :orig_initialize :initialize
    def initialize
      orig_initialize
      @lv=0
    end
  end
  class Item
    # 对物品进行分类
    # 0--食物
    # 1--药物
    # 2--其他
    attr_accessor :type
    def initialize
      super
      @type=0
    end
    def type
      if self.id<=7 or self.id==17
        return 0
      end
      if self.id>7 and self.id<=10
        return 1
      end
      if self.id>10 and self.id != 17
        return 2
      end
    end
  end
end
