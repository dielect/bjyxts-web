WebMod.edit 15 do |m|
  m.npc 13, 13, fight: { enemy: 144, loot: [[:item, 23]], morality: [-10, -5], switch: 105 },
        look: { age: 6, level: 47, attack: 1, items: '破衣烂衫、竹棒',
                text: '一个衣衫褴褛的老叫化，倚着墙根晒太阳。手里那根竹棒被磨得油光发亮，像是用了几十年。他偶尔抬眼看人，目光却清亮得不像个乞丐。' } do |c|
    c.if_switch(104) do
      c.text '棒法要勤加练习，可别丢了老叫化的脸。'
      c.text '记住，打狗棒法只打恶狗，不欺良善。'
    end.else do
      c.if_switch(103) do
        c.if_variable(39, 50, 1) do                  # 基本棍法 ≥ 50
          c.text '老叫化接过竹杖，手指在杖身上轻轻摩挲，半晌没有说话。'
          c.text '好！正是这根绿玉竹杖！少侠果然信人。'
          c.text '实不相瞒，老叫化年轻时也算有些名头。这套“打狗棒法”，今日便传给你了。'
          c.if_variable(84, 0) { c.variable(84, 1) }
          c.switch(104)
          c.text '你学会了打狗棒法！装备棍棒、启用打狗棒法后，便能使出绝技「天下无狗」。'
        end.else do
          c.text '竹杖找回来了？好，好……老叫化瞧瞧。'
          c.text '你这手棍法，连只野狗都赶不走。练到五十级再来找我。听说客栈里的独行大侠什么兵器都会使。'
        end
      end.else do
        c.if_switch(102) do
          c.text '五指山东边的山崖下，有老叫化当年丢的一根绿玉竹杖。'
          c.text '那地方杂草齐腰深，你仔细踩一踩，就能找着。'
        end.else do
          c.if_script('$game_variables[157] < 16') do
            c.text '小娃娃，回家吃饭去吧，莫在街上乱跑。'
          end.else do
            c.if_script('$game_variables[160] < 128') do
              c.text '老叫化眯着眼把你从头打量到脚，摇摇头，翻个身又睡了。'
            end.else do
              c.if_script("#{DAGOU_FOOD_IDS}.any? { |i| $game_party.item_number(i) > 0 }") do
                c.text '行行好，给口吃的吧……老叫化三天没正经吃过东西了。'
                c.choices(%w[施舍 算了]) do |i|
                  next unless i == 0
                  c.script "i = #{DAGOU_FOOD_IDS}.find { |k| $game_party.item_number(k) > 0 }\n$game_party.lose_item(i, 1)"
                  c.variable(161, 1, 1)
                  c.if_variable(161, 3, 1) do
                    c.text '老叫化吃饱了，抹抹嘴，第一次正眼看你：“少侠三番两次相助，看来是个心善的。”'
                    c.text '老叫化年轻时在五指山东边的山崖下丢了一根绿玉竹杖，少侠若能替我找回来，必有重谢。'
                    c.switch(102)
                  end.else do
                    c.if_variable(161, 2) do
                      c.text '老叫化接过吃食，低声嘟囔：“好心人……可惜那根杖子……”说到一半又住了口。'
                    end.else do
                      c.text '多谢少侠，好人有好报啊。'
                    end
                  end
                end
              end.else do
                c.text '行行好，给口吃的吧……（你身上没有吃的）'
              end
            end
          end
        end
      end
    end
  end

