# 商业街：老乞丐、棍棒摊
#--------------------------------------------------------------------------
DAGOU_FOOD_IDS = '(1..7)'                            # 烤鸡腿、包子、酥油茶、翡翠豆腐、猪肉、糖葫芦、白玉豆腐

WebMod.edit 15 do |m|
  m.npc 12, 13, name: '老乞丐', tile: 835,
        look: { age: 6, level: 2, attack: 1, items: '破衣烂衫',
                text: '一个衣衫褴褛的老叫化，手里总攥着根光溜溜的竹棒。' } do |c|
    c.if_switch(104) do
      c.text '棒法要勤加练习，可别丢了老叫化的脸。'
    end.else do
      c.if_switch(103) do
        c.if_variable(39, 50, 1) do                  # 基本棍法 ≥ 50
          c.text '好！正是这根绿玉竹杖！少侠果然信人。'
          c.text '老叫化无以为报，这套“打狗棒法”，今日便传给你了。'
          c.if_variable(84, 0) { c.variable(84, 1) }
          c.switch(104)
          c.text '你学会了打狗棒法！装备棍棒、启用打狗棒法后，便能使出绝技「天下无狗」。'
        end.else do
          c.text '竹杖找回来了？好，好。'
          c.text '可你的基本棍法还不到火候，练到五十级再来找我。听说客栈里的独行大侠什么兵器都会使。'
        end
      end.else do
        c.if_switch(102) do
          c.text '五指山东边的山崖下，有老叫化丢的一根绿玉竹杖，就劳烦你跑一趟了。'
        end.else do
          c.if_script('$game_variables[160] >= 128 && $game_variables[157] >= 16') do
            c.if_script("#{DAGOU_FOOD_IDS}.any? { |i| $game_party.item_number(i) > 0 }") do
              c.text '行行好，给口吃的吧……'
              c.choices(%w[施舍 算了]) do |i|
                next unless i == 0
                c.script "i = #{DAGOU_FOOD_IDS}.find { |k| $game_party.item_number(k) > 0 }\n$game_party.lose_item(i, 1)"
                c.variable(161, 1, 1)
                c.if_variable(161, 3, 1) do
                  c.text '少侠三番两次相助，看来是个心善的。'
                  c.text '老叫化年轻时在五指山东边的山崖下丢了一根绿玉竹杖，少侠若能替我找回来，必有重谢。'
                  c.switch(102)
                end.else do
                  c.text '多谢少侠，好人有好报啊。'
                end
              end
            end.else do
              c.text '行行好，给口吃的吧……（你身上没有吃的）'
            end
          end.else do
            c.text '去去去，别挡着老叫化晒太阳。'
          end
        end
      end
    end
  end

  m.npc 20, 17, name: '棍棒摊主', tile: 872,
        talk: ['上好的白蜡杆、熟铜棍，练棍法的少侠来瞧瞧！'],
        look: { age: 4, level: 1, attack: 1, items: '布衣', text: '一个膀大腰圆的汉子，摊子上横七竖八堆着各色棍棒。' },
        shop: [[:weapon, 31], [:weapon, 32]]
end

#--------------------------------------------------------------------------
# 五指山：东边山崖下的绿玉竹杖
#--------------------------------------------------------------------------
WebMod.edit 24 do |m|
  # 踩上去触发（隐形事件按确定键只能站在上面触发，玩家不好找）。
  # 只在找竹杖期间有反应，平时走过去什么也不发生。
  m.event 18, 5, name: '草丛', trigger: 1 do |c|
    c.if_script('$game_switches[102] && !$game_switches[103]') do
      c.text '拨开草丛，一截碧绿的竹杖露了出来。'
      c.gain(:weapon, 33)
      c.switch(103)
      c.text '得到了绿玉竹杖！'
    end
  end
end
