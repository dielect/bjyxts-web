#------------------------------------------------------------------------------
#  补完原版预留但没做完的棍法线：棍类武器、打狗棒法、绝招「天下无狗」，以及一条小支线。
#
#  流程：
#    1. 商业街路边的老乞丐（隐居的丐帮高手，能战斗）。道德值 ≥ 128 且年龄 ≥ 16 时，可以施舍食物（物品 1～7）；
#    2. 施舍满三次后，老乞丐托你去五指山东边的山崖下找回绿玉竹杖；
#    3. 带着竹杖回来，基本棍法 ≥ 50 级时，老乞丐传授打狗棒法。
#       装备棍类武器、启用打狗棒法后，自动学会绝招「天下无狗」。
#  基本棍法可以跟客栈的独行大侠学；齐眉棍、熟铜棍在商业街的棍棒摊买。
#
#  编号（登记见 docs/内容设计思路.md 0.4 的分配表）：
#    开关 102 施舍满三次  103 找到绿玉竹杖  104 已传授打狗棒法  105 老乞丐已死
#    变量 161 施舍次数
#    武器 31～33  绝招 28  物品 23  敌人 / 敌群 144
#==============================================================================

