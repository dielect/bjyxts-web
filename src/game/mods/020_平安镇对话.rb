# 平安镇东：民团团丁
#--------------------------------------------------------------------------
WebMod.edit 5 do |m|
  m.talk '民团团丁' do |c|
    c.if_good do
      c.random(3) do |i|
        case i
        when 0
          c.text '平安镇平安镇，有我们民团在，保管平平安安。'
        when 1
          c.if_dead(122) do
            c.text '西郊的流氓头被人收拾了，那帮小喽啰总算消停了些。'
          end.else do
            c.text '西郊那帮流氓又在闹事。流氓头不出面，底下的小喽啰谁也管不住。'
          end
        when 2
          c.if_dead(27) do
            c.text '听说北郊的采花大盗栽了，镇上的大姑娘们总算敢出门了。'
          end.else do
            c.text '北郊有个采花大盗，轻功好得很，官府通缉了好几年都没抓着。'
          end
        end
      end
    end.else do
      c.text '站住！看你贼眉鼠眼的，最近镇上丢鸡丢狗，是不是你干的？'
    end
  end
end

