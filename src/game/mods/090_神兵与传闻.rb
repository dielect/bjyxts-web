TREASURES.each do |sw, map, x, y, name, what, _, _, found|
  next unless map
  taken = sw + 1
  WebMod.edit map do |m|
    m.event x, y, name: name, trigger: 1 do |c|
      c.if_script("$game_switches[#{sw}] && !$game_switches[#{taken}]") do
        case what
        when :yitian
          c.text '石墩旁坐着一位白发老尼，闭目不语，膝上横着一口古剑。'
          c.text '“倚天剑不出，谁与争锋。施主想取剑，先过贫尼这一关。”'
          c.choices(%w[请赐教 告辞]) do |i|
            if i == 0
              c.fight(153, can_escape: false,
                spared: lambda {
                  c.text '老尼长叹一声，双手捧起古剑：“剑归有德。望施主好自为之。”'
                  c.gain(:weapon, 52); c.switch(taken); c.text '得到了倚天剑！'
                },
                killed: lambda {
                  c.text '老尼倒在石墩旁。你从她膝上取下了那口剑，心里却空落落的。'
                  c.gain(:weapon, 52); c.switch(taken); c.reward morality: -15
                  c.text '得到了倚天剑。'
                },
                lose: -> { c.text '老尼收剑入鞘：“施主再练十年，再来不迟。”' })
            else
              c.text '老尼依旧闭目，仿佛你从没来过。'
            end
          end
        when :jinshe
          c.text '洞口阴风阵阵，地上爬满了金色的小蛇，洞里隐约供着一口弯弯曲曲的剑。'
          c.choices(%w[硬闯进去 算了]) do |i|
            if i == 0
              c.script "a = $game_actors[1]\na.hp = [a.hp - a.maxhp * 3 / 10, 1].max"
              c.text '你咬着牙冲进洞里，被金蛇咬了好几口，总算抢出了那口金蛇剑！'
              c.gain(:weapon, 72); c.switch(taken)
              c.text '得到了金蛇剑！（气血损失三成）'
            else
              c.text '你在洞口站了半天，终究没敢进去。'
            end
          end
        else
          c.text found
          what.each { |kind, id, _| c.gain(kind, id) }
          c.switch(taken)
          c.text "得到了#{what.map { |*, n| n }.join('、')}！"
        end
      end
    end
  end
end

